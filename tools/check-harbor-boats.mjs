import assert from 'node:assert/strict';
import {defaultState} from '../src/state.js';
import {HARBOR_BOAT_DOCK,HARBOR_BOAT_EXIT,HARBOR_WATER_BOUNDS,BOAT_RENT_DREAMBUCKS,
 BOAT_BUY_DREAMBUCKS,normalizeBoatState,ensureBoatState,boatWaterPosition,boatObstructed,
 boardHarborBoat,dockHarborBoat,canDockBoat,serviceDockedBoat,stepHarborBoat,requestHarborBoatRescue}
 from '../src/runtime/HarborBoatLife.js';
import {inFishingHarbor,harborSafePoint} from '../src/config/fishingHarborPlan.js';
import {readFileSync,existsSync} from 'node:fs';
assert(inFishingHarbor(HARBOR_BOAT_DOCK));
assert(!boatObstructed(HARBOR_BOAT_DOCK));
assert.deepEqual(harborSafePoint(HARBOR_BOAT_EXIT),HARBOR_BOAT_EXIT);
const state=defaultState(),startCash=state.money;
assert.equal(ensureBoatState(state).fuel,100);
assert(boardHarborBoat(state).ok);
assert.equal(state.money,startCash-BOAT_RENT_DREAMBUCKS);
const startZ=state.boating.z;
assert(stepHarborBoat(state.boating,{f:1},.05).moved);
assert(state.boating.z<startZ);
for(let i=0;i<160;i++)stepHarborBoat(state.boating,{f:1},.05);
assert(state.boating.z<startZ-25);
assert(!dockHarborBoat(state).ok,'boat away from slip must not disembark');
assert.equal(boatWaterPosition({x:9000,z:-8000}).x,HARBOR_WATER_BOUNDS.maxX);
assert.equal(boatWaterPosition({x:9000,z:-8000}).z,HARBOR_WATER_BOUNDS.minZ);
assert(boatObstructed({x:120,z:-2900}));
assert(boatObstructed({x:550,z:-3180}));
Object.assign(state.boating,{x:HARBOR_BOAT_DOCK.x,z:HARBOR_BOAT_DOCK.z,speed:0});
Object.assign(state.boating,{x:HARBOR_BOAT_DOCK.x+30,z:HARBOR_BOAT_DOCK.z-10,yaw:0,speed:1});
assert(canDockBoat(state.boating));assert(dockHarborBoat(state).ok);
assert.deepEqual({x:state.boating.x,z:state.boating.z},HARBOR_BOAT_DOCK);
assert.equal(state.boating.yaw,Math.PI);
assert.equal(state.boating.speed,0);
assert.equal(state.boating.riding,false);
assert.deepEqual(normalizeBoatState(JSON.parse(JSON.stringify(state.boating))),state.boating);
const m=state.money;assert(boardHarborBoat(state).ok);assert.equal(state.money,m);
assert(dockHarborBoat(state).ok);state.day=2;
const m2=state.money;assert(boardHarborBoat(state).ok);
assert.equal(state.money,m2-BOAT_RENT_DREAMBUCKS);assert(dockHarborBoat(state).ok);
state.boating.fuel=20;state.boating.hull=80;
const service=serviceDockedBoat(state);
assert(service.ok&&service.cost>0&&state.boating.fuel===100&&state.boating.hull===100);
state.day=3;
state.boating.fuel=10;state.boating.hull=40;
const expiredCash=state.money;
assert.deepEqual(serviceDockedBoat(state),{ok:true,cost:0});
assert.equal(state.money,expiredCash);
assert(boardHarborBoat(state).ok);
assert.equal(state.money,expiredCash-BOAT_RENT_DREAMBUCKS);
assert.equal(state.boating.fuel,100);
assert.equal(state.boating.hull,100);
const freeService=defaultState();
freeService.boating=normalizeBoatState({owned:true});
delete freeService.money;
assert.deepEqual(serviceDockedBoat(freeService),{ok:true,cost:0});
assert.equal(freeService.money,undefined,'free service must not corrupt a missing legacy balance');
const poor=defaultState();poor.money=0;
assert.equal(boardHarborBoat(poor).reason,'need-rental-funds');
assert.equal(poor.boating.riding,false);
const buyer=defaultState();assert(boardHarborBoat(buyer,{purchase:true}).ok);
assert.equal(buyer.money,500-BOAT_BUY_DREAMBUCKS);assert(buyer.boating.owned);
assert(normalizeBoatState(JSON.parse(JSON.stringify(buyer.boating))).riding);
assert(!normalizeBoatState({riding:true}).riding);
// Corrupt/legacy saves that put a moving boat inside a pier must not
// respawn at the marina with stale velocity and drift into another obstacle.
const recoveredPier=normalizeBoatState({owned:true,riding:true,x:550,z:-3180,speed:18});
assert.deepEqual({x:recoveredPier.x,z:recoveredPier.z},HARBOR_BOAT_DOCK);
assert.equal(recoveredPier.speed,0,'invalid saved boat position must cancel momentum');
assert.equal(recoveredPier.riding,true,'recovery must preserve occupied boat');
assert.equal(normalizeBoatState({owned:true,riding:true,x:400,z:-3410,speed:4}).speed,4,
 'valid mid-water saves must preserve speed');
const recoveredBoundary=normalizeBoatState({owned:true,riding:true,x:9000,z:-8000,speed:18});
assert.deepEqual({x:recoveredBoundary.x,z:recoveredBoundary.z},{x:HARBOR_WATER_BOUNDS.maxX,z:HARBOR_WATER_BOUNDS.minZ});
assert.equal(recoveredBoundary.speed,0,'clamped saves must cancel stale momentum');
assert.equal(recoveredBoundary.riding,true);
for(const coords of [{x:undefined,z:-3410},{x:400,z:null},{x:'9000',z:-3410},{x:400,z:NaN}]){
 const recovered=normalizeBoatState({owned:true,riding:true,speed:12,...coords});
 assert.equal(recovered.speed,0,'malformed coordinates must cancel momentum');
 assert.equal(recovered.riding,true);
 assert(Number.isFinite(recovered.x)&&Number.isFinite(recovered.z));
}
// Never strand an owner or renter at sea after damage, exhaustion or an old save.
const stranded=defaultState();
stranded.money=0;
stranded.boating={...normalizeBoatState({owned:true,riding:true,x:400,z:-3410,fuel:0,hull:0})};
assert.equal(dockHarborBoat(stranded).ok,false);
const rescue=requestHarborBoatRescue(stranded);
assert(rescue.ok&&rescue.fee===0);
assert(canDockBoat(stranded.boating));
assert(stranded.boating.fuel>=25&&stranded.boating.hull>=35);
assert(stranded.boating.riding,'rescue must preserve vehicle occupancy until F disembark');
assert(dockHarborBoat(stranded).ok);
const rescuer=defaultState();
rescuer.boating={...normalizeBoatState({owned:true,riding:true,x:-500,z:-3400})};
const rescueCash=rescuer.money;
assert.equal(requestHarborBoatRescue(rescuer).fee,25);
assert.equal(rescuer.money,rescueCash-25);
assert.equal(requestHarborBoatRescue(rescuer).fee,0,'repeat tow at safe marina must not charge');
assert.equal(rescuer.money,rescueCash-25);
rescuer.boating.fuel=0;
assert.equal(requestHarborBoatRescue(rescuer).fee,25,'disabled boat at marina still receives assistance');
assert.equal(rescuer.boating.fuel,25);
assert.equal(normalizeBoatState({fuel:999,hull:-1}).fuel,100);
const braking=normalizeBoatState({owned:true,riding:true,x:400,z:-3410,speed:.2});
stepHarborBoat(braking,{f:-1},.05);
assert.equal(braking.speed,0,'opposing throttle must stop before reversing');
stepHarborBoat(braking,{f:-1},.05);
assert(braking.speed<0,'held reverse must still engage after stopping');
braking.speed=-.2;
stepHarborBoat(braking,{f:1},.05);
assert.equal(braking.speed,0,'forward throttle must stop reverse momentum first');
stepHarborBoat(braking,{f:1},.05);
assert(braking.speed>0);
const main=readFileSync(new URL('../src/main.js',import.meta.url),'utf8');
assert.match(main,/stepHarborBoat\(boat,controls\.moveInput\(\),dt\)/);
assert.match(main,/if\(inBoat\) updateHarborBoat\(dt\)/);
assert.match(main,/const savedPosition=inBoat\?/);
assert.match(main,/case 'boats':/);
assert.match(main,/requestHarborBoatRescue\(state\)/,'player must be able to call water rescue from input');
assert(existsSync(new URL('../public/assets/models/generated/fishing-harbor/modular_prop/vehicle_harbor_rental_boat_a_v01.glb',import.meta.url)));
console.log('[harbor-boats] water physics, pier collisions, boat purchase/rent, service, saves and existing authored GLB checks passed');
