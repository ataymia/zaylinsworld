import assert from 'node:assert/strict';
import { readFile } from 'node:fs/promises';
import vm from 'node:vm';

const source = await readFile('src/controls.js', 'utf8');
const listeners = new Map();
const listen = (type, fn) => listeners.set(type, [...(listeners.get(type) || []), fn]);
const fire = (type, event = {}) => { for (const fn of listeners.get(type) || []) fn(event); };
const domListeners = new Map();
const dom = { addEventListener: (type, fn) => domListeners.set(type, fn) };
const context = vm.createContext({ THREE: {}, window: { addEventListener: listen }, document: { addEventListener() {}, pointerLockElement: null }, Set, Math });
const code = source.replace(/^import .*?;\s*/m, '').replace(/export const CAM/, 'const CAM').replace(/export class Controls/, 'class Controls') + '\nthis.Controls = Controls;';
new vm.Script(code, { filename: 'controls.js' }).runInContext(context);
const controls = new context.Controls({}, dom);
const key = (k, target = { tagName: 'CANVAS' }, extras = {}) => ({ key: k, target, preventDefault() { this.prevented = true; }, ...extras });
fire('keydown', key('w'));
assert.equal(controls.moveInput().f, 1);
fire('keydown', key('Shift'));
assert.equal(controls.moveInput().run, true);
fire('keydown', key(' ', { tagName: 'INPUT' }));
assert.equal(controls.moveInput().jump, false);
fire('keydown', key('ArrowUp', { tagName: 'TEXTAREA' }));
assert.equal(controls.moveInput().f, 1);
fire('keydown', key('d', { tagName: 'DIV', isContentEditable: true }));
assert.equal(controls.moveInput().s, 0);
fire('keydown', key('s', { tagName: 'CANVAS' }, { ctrlKey: true }));
assert.equal(controls.moveInput().f, 1);
fire('keyup', key('w'));
assert.equal(controls.moveInput().f, 0);
assert.equal(controls.consumePress('w'), true, 'quick taps survive until frame consumption');
fire('keydown', key('w'));
domListeners.get('mousedown')({ button: 0 });
assert.equal(controls.mouseHeld(0), true);
fire('blur');
assert.equal(controls.moveInput().f, 0);
assert.equal(controls.moveInput().run, false);
assert.equal(controls.mouseHeld(0), false);
assert.equal(controls.consumeClick(0), false);
assert.equal(controls.consumePress('w'), false);
fire('keydown', key('ArrowUp'));
assert.equal(controls.moveInput().f, 1);
console.log('[controls] typing, shortcuts, quick taps, focus-loss recovery verified');
