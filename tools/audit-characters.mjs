import { mkdir, readFile, stat, writeFile } from 'node:fs/promises';
import path from 'node:path';

const ROOT = process.cwd();
const INDEX_PATH = path.join(ROOT, 'public/assets/models/asset-index-v2.json');
const OUT_DIR = path.join(ROOT, 'artifacts');
const REPORT_PATH = path.join(OUT_DIR, 'CHARACTER_ASSET_AUDIT.md');
const JSON_PATH = path.join(OUT_DIR, 'character-asset-audit.json');

function parseGlb(buffer) {
  if (buffer.length < 20 || buffer.toString('utf8', 0, 4) !== 'glTF') {
    throw new Error('not a GLB 2.0 file');
  }
  const version = buffer.readUInt32LE(4);
  if (version !== 2) throw new Error(`unsupported GLB version ${version}`);
  let offset = 12;
  while (offset + 8 <= buffer.length) {
    const length = buffer.readUInt32LE(offset);
    const type = buffer.readUInt32LE(offset + 4);
    offset += 8;
    if (offset + length > buffer.length) throw new Error('truncated GLB chunk');
    if (type === 0x4E4F534A) {
      return JSON.parse(buffer.toString('utf8', offset, offset + length).replace(/\u0000+$/g, ''));
    }
    offset += length;
  }
  throw new Error('GLB JSON chunk missing');
}

async function readGltf(file) {
  const buffer = await readFile(file);
  if (file.toLowerCase().endsWith('.glb')) return parseGlb(buffer);
  return JSON.parse(buffer.toString('utf8'));
}

function positionBounds(gltf) {
  const accessors = gltf.accessors || [];
  const meshes = gltf.meshes || [];
  const mins = [Infinity, Infinity, Infinity];
  const maxs = [-Infinity, -Infinity, -Infinity];
  let count = 0;
  for (const mesh of meshes) {
    for (const primitive of mesh.primitives || []) {
      const accessorIndex = primitive.attributes?.POSITION;
      const accessor = Number.isInteger(accessorIndex) ? accessors[accessorIndex] : null;
      if (!accessor || !Array.isArray(accessor.min) || !Array.isArray(accessor.max)) continue;
      for (let i = 0; i < 3; i++) {
        mins[i] = Math.min(mins[i], accessor.min[i]);
        maxs[i] = Math.max(maxs[i], accessor.max[i]);
      }
      count++;
    }
  }
  if (!count) return null;
  return {
    min: mins,
    max: maxs,
    size: maxs.map((value, i) => value - mins[i]),
  };
}

function classify(row) {
  if (row.error) return 'reject-broken-file';
  if (!row.meshes) return 'reject-no-meshes';
  if (row.skins > 0 && row.animations > 0) return 'rigged-with-clips';
  if (row.skins > 0) return 'valid-skin-no-clips';
  if (row.animations > 0) return 'needs-retarget-animated-no-skin';
  return 'static-prop-only';
}

function esc(value) {
  return String(value ?? '').replaceAll('|', '\\|').replaceAll('\n', ' ');
}

const index = JSON.parse(await readFile(INDEX_PATH, 'utf8'));
const packs = index.characters || {};
const rows = [];

for (const [pack, entries] of Object.entries(packs)) {
  for (const entry of entries) {
    const rel = entry.path.startsWith('models/') ? entry.path : `models/${entry.path}`;
    const file = path.join(ROOT, 'public/assets', rel);
    const row = {
      pack,
      name: entry.name,
      path: `public/assets/${rel}`,
      type: entry.type || path.extname(file).slice(1),
      bytes: 0,
      meshes: 0,
      nodes: 0,
      skins: 0,
      animations: 0,
      clips: [],
      bounds: null,
      error: '',
    };
    try {
      const info = await stat(file);
      row.bytes = info.size;
      const gltf = await readGltf(file);
      row.meshes = gltf.meshes?.length || 0;
      row.nodes = gltf.nodes?.length || 0;
      row.skins = gltf.skins?.length || 0;
      row.animations = gltf.animations?.length || 0;
      row.clips = (gltf.animations || []).map((clip, i) => clip.name || `unnamed-${i + 1}`);
      row.bounds = positionBounds(gltf);
    } catch (error) {
      row.error = error?.message || String(error);
    }
    row.classification = classify(row);
    rows.push(row);
  }
}

rows.sort((a, b) => a.pack.localeCompare(b.pack) || a.name.localeCompare(b.name));
const totals = {};
for (const row of rows) totals[row.classification] = (totals[row.classification] || 0) + 1;

const lines = [
  '# Character Asset Audit',
  '',
  '_Generated by `npm run audit:characters` from the committed runtime asset index._',
  '',
  '## Summary',
  '',
  `- Character assets indexed: **${rows.length}**`,
  `- Total runtime size: **${(rows.reduce((sum, row) => sum + row.bytes, 0) / 1024 / 1024).toFixed(1)} MB**`,
  ...Object.entries(totals).sort().map(([key, value]) => `- ${key}: **${value}**`),
  '',
  '## Classification rules',
  '',
  '- `rigged-with-clips`: at least one glTF skin and one animation clip.',
  '- `valid-skin-no-clips`: skinned mesh suitable for static/externally animated skin use.',
  '- `needs-retarget-animated-no-skin`: animation data exists without a glTF skin.',
  '- `static-prop-only`: meshes exist but no skin or clips.',
  '- `reject-*`: missing, malformed, or meshless runtime file.',
  '',
  'Accessor bounds are a source-space estimate. Final in-game validation must still normalize and measure the instantiated Three.js object before hiding the procedural fallback.',
  '',
  '## Assets',
  '',
  '| Pack | Name | Size | Meshes | Skins | Clips | Position bounds | Classification | Error |',
  '|---|---|---:|---:|---:|---:|---|---|---|',
];

for (const row of rows) {
  const bounds = row.bounds ? row.bounds.size.map((n) => Number(n).toFixed(2)).join(' × ') : 'unknown';
  lines.push(`| ${esc(row.pack)} | ${esc(row.name)} | ${(row.bytes / 1024).toFixed(0)} KB | ${row.meshes} | ${row.skins} | ${row.animations}${row.clips.length ? ` (${esc(row.clips.join(', '))})` : ''} | ${bounds} | ${row.classification} | ${esc(row.error)} |`);
}

await mkdir(OUT_DIR, { recursive: true });
await writeFile(REPORT_PATH, `${lines.join('\n')}\n`);
await writeFile(JSON_PATH, `${JSON.stringify({ generatedAt: new Date().toISOString(), totals, rows }, null, 2)}\n`);
console.log(`[character-audit] wrote ${path.relative(ROOT, REPORT_PATH)} and ${path.relative(ROOT, JSON_PATH)} (${rows.length} assets)`);
